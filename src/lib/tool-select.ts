/**
 * P3 · **按需注册**：这一轮该把哪些动作当 `tools` 发给上游？
 *
 * 为什么必须做（上一轮实测的账，见交接文档 ⑤ §2.5）：
 *   61 个动作的 tools 定义**每轮都要发 ≈ 4007 token** —— 比"提示词里省下的 2023"多得多。
 *   发一大堆这次根本用不上的工具，既费钱又会让模型选错。
 *
 * 用户原话（P3 的需求）："就是根据对话判断我需要什么样的工具才会调用，
 * 其他的就不每一轮都发给它" / "就是只根据对话发需要的工具，其他无关的不带进去"。
 *
 * ── 三条边界（这个文件最容易犯的错都在这儿）────────────────────────
 *
 * 1. **漏发的代价远大于多发**：少给一个动作，他的反应是"这个我做不到"（用户会以为功能坏了）；
 *    多发几个只是多花一点 token。所以规则要**偏召回**（宁可多给）：
 *    命中一个词就给整组，绝不做"精确到一个动作"的吝啬匹配。
 *
 * 2. **`emotion.report`（「自我」组）永远要带**：那是「星屿」情绪灵体的数据来源，
 *    漏一轮就等于那一轮的情绪缺一块。这条跟"相关不相关"无关，是硬要求。
 *    （2026-10 之前这条说的是旧的 `state.report`／11 维花瓣 —— 那个动作已整条退场。）
 *
 * 3. **`navigate` 的分量被低估**：用户说"我要去看那个""回到刚才那个页面"时，
 *    字面上一个关键词都匹配不到，但"带我去"类动作是最常用的 —— 所以它也在常驻集合里，
 *    而且**任何**模型给出的路径都要在客户端验一遍（见 `actions.ts`）。
 *
 * 这个文件**零 import**（纯粹给 `node --experimental-strip-types` 直接跑，
 * `verify-tool-recall.mjs` 拿它跟 60 句真句子对账）。
 */

