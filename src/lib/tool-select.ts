export type SelectToolsInput = {
  /** 用户这句话（最后一轮） */
  text: string;
  /** 最近的对话（新→旧），用来兜住"他上一句说要做什么"这种跨轮上下文 */
  recent?: string[];
  /**
   * 这个动作**该不该发**（返回 false = 不发）。
   *
   * 为什么做成回调而不是直接读 `permissions`：动作 → 权限的映射在
   * `action-meta.ts`（`ACTION_PERMISSION`），而这个文件要保持**零 import**
   * 才能在纯 node 里跑。调用方传 `(kind) => permissions[ACTION_PERMISSION[kind]] !== "deny"`。
   */
  allowed?: (kind: string) => boolean;
  /** 这一轮到底有哪些动作可用（默认：全部） */
  allKinds?: string[];
  /** 每个动作属于哪一组（默认：`action-schema` 那份） */
  groupOf?: Record<string, GroupId>;
  /** `false` = 不做筛选，全发（用户在设置里关掉了按需） */
  enabled?: boolean;
};

export type SelectToolsResult = {
  /** 这一轮要发的动作 kind（顺序稳定，便于断言 + 前缀缓存） */
  kinds: string[];
  /** 命中的组（诊断/界面显示用） */
  groups: GroupId[];
  /** 筛掉了几个（诊断用） */
  dropped: number;
};

/**
 * 诊断用：哪些词把哪些组点着了（"他怎么会给这一组"就靠它回答）。
 * 规则调参时必须能看见这个，否则只能猜（第一版就是靠猜，错了三轮）。
 */
export function explainSelection(input: SelectToolsInput): Record<string, string[]> {
  const haystack = normalize([input.text, ...(input.recent ?? [])].join("\n"));
  const out: Record<string, string[]> = {};
  for (const g of ALL_GROUPS) {
    const hit = GROUP_KEYWORDS[g].filter((w) => haystack.includes(normalize(w)));
    if (hit.length) out[g] = hit;
  }
  return out;
}

/** 归一化：小写 + 全角转半角（"ＭＰＣ"、"Ｍusic" 这种也要认） */
function normalize(text: string): string {
  return (text ?? "")
    .toLowerCase()
    .replace(/[\uFF01-\uFF5E]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0xfee0));
}

/**
 * 挑这一轮要发的动作。
 *
 * 顺序：先常驻 → 再看关键词命中的组 → 再按权限砍掉被拒的。
 * （顺序固定，别用 Set 的遍历顺序 —— 那会让同样的输入产生不同的 tools 顺序，
 *  白白打断上游的前缀缓存。）
 */
/**
 * 判定"这句话的意思够不够明确"。
 *
 * 走过的弯路（三轮才定下来，都留着当教训）：
 *   ① 只按"命中组数 >= 2"判 → 一个域内说得再具体也只命中 1 组（"七点半叫我起床"）
 *      → 被当成"不明确"→ 全发 → **6 句测试里 5 句一个 token 都没省**（白做）
 *   ② 改成"1 组 + 组内 >= 2 个词"→ 实测 38 句里只有 9 句能筛（平均还发 49.6 个），
 *      省得动但省得少 —— 因为口语里很多话**只带一个域内特征词**（"七点半叫我起床"只有"叫我"）
 *
 * 最终定下来的判据：**命中 >= 1 个词就筛**。
 * 为什么敢这么松：筛错（多用了一次工具）的代价 ≈ 0
 *   · 多给一组 ≠ 会被调用 —— 模型只为**当前这句话**挑工具，不会顺手乱调
 *   · 少给一组 ≠ 功能没了 —— 提示词里有兜底规则 + 全量动作名（见 `FALLBACK_RULE`）
 * 而"一个词都没命中"（"嗯，就这样"）才是真的不知道要什么 → **全发**。
 */
const MIN_HIT_WORDS = 1;

export function selectActionKinds(input: SelectToolsInput): SelectToolsResult {
  const all = input.allKinds ?? [];
  const groupOf = input.groupOf ?? {};
  const always = new Set<string>(ALWAYS_KINDS);
  const allowed = input.allowed ?? (() => true);

  const everything = (groups: GroupId[]): SelectToolsResult => {
    const kinds = all.filter((k) => allowed(k));
    return { kinds, groups, dropped: all.length - kinds.length };
  };

  if (input.enabled === false) return everything([...ALL_GROUPS]);

  /** 把"这句话 + 最近几轮"拼起来找关键词（跨轮上下文：他上一条说要记日记，这条只说"好"） */
  const haystack = normalize([input.text, ...(input.recent ?? [])].join("\n"));

  const hit = new Set<GroupId>();
  /** 命中了**几个词**（同一个词只算一次，免得"提醒我"+"提醒"重复计数） */
  let words = 0;
  for (const g of ALL_GROUPS) {
    const matched = GROUP_KEYWORDS[g].filter((w) => haystack.includes(normalize(w)));
    if (matched.length === 0) continue;
    hit.add(g);
    words += matched.length;
  }

  /** 一个特征词都没命中 = 真不知道他要什么 → 全发（这一轮不省，但绝不漏） */
  if (words < MIN_HIT_WORDS) return everything([...ALL_GROUPS]);

  /**
   * 命中的**整组**都发 —— 简单、可解释、不会漏（见文件头第 1 条）。
   * 不做"精确到某个动作"的吝啬匹配：少给一个动作的代价比多花几百 token 大得多。
   */
  const kinds = all.filter((k) => {
    if (!allowed(k)) return false;
    if (always.has(k)) return true;
    const g = groupOf[k];
    return Boolean(g && hit.has(g));
  });

  return {
    kinds,
    groups: ALL_GROUPS.filter((g) => hit.has(g)),
    dropped: all.length - kinds.length,
  };
}

/**
 * 给模型看的"兜底"说明 —— 按需注册最关键的一块**安全网**。
 *
 * 为什么要它：筛掉的动作 != 不存在的能力。用户在设置里能关掉按需，
 * 但**他这一轮恰好要用的动作没被选中**时，模型不能回答"我做不到"
 * —— 那会让用户以为功能坏了（而其实只是这轮没带）。
 *
 * 所以提示词里始终保留动作**名字**（只给名字，不给参数结构，很便宜），
 * 并明确告诉他：需要清单里没带的动作，就照老协议在正文里写动作块 ——
 * 客户端照样过闸门执行。
 */
export const FALLBACK_RULE = `【这一轮的工具是按需给你的】
你这次收到的工具定义是**按当前对话挑的**，不是全部能力。
下面这份名字清单里，凡是**这轮没带定义**的，你可以直接在回复末尾写动作块来用：
\`\`\`qidao
{"kind":"动作名", ...参数}
\`\`\`
（客户端会照常执行，跟走工具定义的效果一样。）
所以**不要**因为"工具列表里没有"就回答"我做不到" —— 先查这份名字清单，再写动作块。`;

/**
 * 兜底规则后面那份**动作名字清单**（只给名字，不给参数结构）。
 *
 * 为什么只给名字：这是"筛掉的动作 != 不存在"的唯一凭据，
 * 名字很短（62 个约 900 字符 ≈ 250 token），比把参数结构全塞回去便宜一个量级。
 */
export function renderToolNameList(kinds: readonly string[]): string {
  return `全部可用的动作名（逗号分隔）：\n${kinds.join("、")}`;
}
