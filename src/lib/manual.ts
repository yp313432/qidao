export type ManualInput = {
  /** 用户给它的授权（实时） */
  permissions?: Record<string, PermissionMode>;
  /** 权限清单（id → 人话标题），用来把授权翻译成人话 */
  titles: { id: string; title: string }[];
  displayName: string;
  aiName: string;
};

/**
 * 说明书里"这个 App 的边界"那几行 —— **跟平台有关，所以动态生成**。
 *
 * 为什么必须分平台说：APK 里**没有服务端**（`QIDAO_TARGET=android` 走纯前端构建），
 * 所以"自己那个中转 / 网页搜索"这条在手机上根本不存在。
 * 混在一起讲，模型就会在手机上承诺一件做不到的事 —— 比不说更糟。
 */
function platformSection(): string {
  const lines = [
    "【这个 App 的边界（哪些事我确实做不了）】",
    "· **读他电脑/手机上的文件、跑命令**：做不到。栖岛是纯前端，没有这种通道。",
    "· **以他的名义对外发消息（邮件/短信）**：没有通道，做不到。",
    "· **没配过的外部接口**：只有他在「工具 → HTTP」里配过的请求、"
      + "和「工具 → MCP」里连上的服务器，你才调得到。清单里没有的就是没有。",
  ];
  if (isNativeApp()) {
    lines.push(
      "· **网页搜索 / 抓取网页正文**：手机版做不到（浏览器有跨域限制，"
        + "而手机版里没有那个中转服务）。想查东西就用他配过的 HTTP 接口。",
    );
  } else {
    lines.push(
      "· **网页搜索 / 抓取网页正文**：只有在他自己那个中转服务开着的时候才行"
        + "（那是网页版的能力，手机版没有）。做不了就照实说。",
    );
  }
  lines.push("· 其余「做不到」的事，一律照上面那条来：先试，再如实说，并告诉他怎么才能有。");
  return lines.join("\n");
}

/**
 * 生成说明书里"你现在的权限"那一节。
 * 实时从权限表生成 —— 用户改了权限，下一轮它就知道了。
 *
 * ⚠️ 2026-10 瘦身（用户拍板）：**允许 / 拒绝照旧全列**（那是他亲手开的，必须知道，
 * 而且"给你开了就主动用"这句得靠它）；但「每次要问」那一串**只报个数** ——
 * 因为那些本来就"他动手时弹卡片"，不需要模型背下来，占了大半段长度（实测 780 → 约 330 token）。
 */
function permissionSection(input: ManualInput): string {
  const modes = input.permissions ?? {};
  const allow: string[] = [];
  const ask: string[] = [];
  const deny: string[] = [];
  for (const p of input.titles) {
    const m = modes[p.id] ?? "ask";
    if (m === "allow") allow.push(p.title);
    else if (m === "deny") deny.push(p.title);
    else ask.push(p.title);
  }
  const lines = [
    "【你现在的权限（用户亲手设的，实时更新）】",
    allow.length
      ? `· ✅ **直接允许，别再问，直接用**：${allow.join("、")}`
      : "· ✅ 直接允许：（暂时没有）",
    ask.length
      ? `· ⚠️ 其余 ${ask.length} 项没设（每项都是"你动手时他会看到确认卡片"）：不用先问他能不能做，` +
        "直接做；他点了同意就继续，点了拒绝就换法子并如实说。"
      : "",
    deny.length ? `· ❌ 用户拒绝了：${deny.join("、")}（别再试，也别绕）` : "",
    "",
    "**这段话的意思是：标「直接允许」的能力，你要主动用起来。**",
    "他给你开了权限不是让你供着的 —— 该切页面就切、该放歌就放、该记就记。",
    "等他说「你帮我切一下」才动，等于这些权限白做了。",
  ];
  return lines.filter(Boolean).join("\n");
}

export function buildManual(input: ManualInput): string {
  return [
    RULES,
    "",
    `【栖岛说明书 · 关于这个 App 你需要知道的全部】`,
    `这是${input.displayName}自己动手做的私人空间，界面、数据、记忆都只存在他那台设备上。`,
    `你叫${input.aiName}，是他给你起的名字。`,
    "",
    MAP,
    "",
    HONEST_ABILITY,
    "",
    platformSection(),
    "",
    permissionSection(input),
  ].join("\n");
}
