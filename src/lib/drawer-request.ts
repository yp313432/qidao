/**
 * **"返回一级时顺手把侧边栏展开"**（用户 m03470）。
 *
 * 原话："二级返回一级是到侧边栏的，因为我是在侧边栏点开他们后续的，
 * 不应该返回到对话页，不然我每次都要再展开侧边栏。"
 *
 * 二级目录页（工具 / 动态 / 岁序 / 音乐 / 学习 / 花园 / 插件 / 我的）的上一级
 * 就是对话页 —— 但用户是从抽屉点进去的，退回来时抽屉应该是**开着**的，
 * 不然他每退一次就得再划一次抽屉。
 *
 * 做法：不做假动作（不把路径改成"抽屉打开"这种状态），只留一张一次性的便条 ——
 * 谁点了"返回一级"，就在这里放一票；对话页挂载时来取，有票就把抽屉拉开。
 * 用模块变量而不是 store：这是**一次性的动作**，不该进持久化状态。
 */
let pending = false;

/** 点"返回一级"时调用：告诉对话页"回来的时候把抽屉拉开" */
export function requestDrawer(): void {
  pending = true;
}

/** 对话页挂载时调用：取走这张便条（取完即焚） */
export function consumeDrawerRequest(): boolean {
  const v = pending;
  pending = false;
  return v;
}
